#!/usr/bin/env node
// _N8N_CONTRACTS_INLINE_v1_ (owner 2026-10-23: "keep all the contracts inline with lang/n8n"): the node's operations that coord's
// language names are GENERATED from it, never hand-typed. coord lang/cue/n8n-resale.cue node_ops → lang/gen/n8n-resale.json →
// `coord gen` (consumer row n8n-resale-node) → coord-lang/n8n-resale.json here. Each op names its gate route (method + op) and
// coord's gate refuses an op that is no route or that drops a field the route requires; this script turns the rows into
// nodes/Taifoon/descriptions/<resource>.generated.ts (declarative routing, the shape every hand-typed file here uses).
//   node scripts/gen-descriptions.mjs           write the generated files
//   node scripts/gen-descriptions.mjs --check   write nothing; exit 1 when a generated file is not what the rows emit, or a
//                                               hand-typed op (hand: true) no longer sends the method and url its route has
// Without coord-lang/n8n-resale.json (the public mirror ships without it) --check says so and exits 0.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'coord-lang', 'n8n-resale.json');
const DESC = join(ROOT, 'nodes', 'Taifoon', 'descriptions');

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lit = (v) => (typeof v === 'string' ? q(v) : JSON.stringify(v));
const byName = (a, b) => a.name.localeCompare(b.name);
const optName = (o) => (/[\d.]/.test(o) && /[A-Z]|^\d/.test(o) ? o : o.split(/[-_ ]/).map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' '));

// _N8N_RETURN_ALL_v1_ (n8n review of 1.2.2): an optional parameter is never top-level. On a GET it is a filter (the op's
// Filters collection), on a body route an Additional Field; a GET's optional `limit` becomes Return All + Limit, read whole by
// the API's own paging, named here per route (its list key, its largest page, how it pages; see descriptions/paging.ts).
const PAGING = { 'GET /n8n/demand': { root: 'rows', max: 200, by: 'cursor' } };
const isLimit = (o, p) => !p.required && o.method === 'GET' && p.type === 'number' && p.property === 'limit';
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const collectionOf = (o) => (o.method === 'GET' ? { name: `${o.resource}${cap(o.operation)}Filters`, display: 'Filters', placeholder: 'Add Filter' } : { name: `${o.resource}${cap(o.operation)}Options`, display: 'Additional Fields', placeholder: 'Add Field' });

/** One parameter: its type, default, the operations it shows on and how it is sent. A path parameter is read by the url. */
function param(resource, ops, p) {
	const lines = [`\t{`, `\t\tdisplayName: ${q(p.display)},`, `\t\tname: ${q(p.name)},`, `\t\ttype: ${q(p.type)},`];
	const dflt = p.default ?? (p.type === 'number' ? 0 : p.type === 'boolean' ? false : '');
	lines.push(`\t\tdefault: ${lit(dflt)},`);
	if (p.required) lines.push(`\t\trequired: true,`);
	if (p.placeholder) lines.push(`\t\tplaceholder: ${q(p.placeholder)},`);
	// an option's name: its words title-cased (n8n's linter), a token with a digit or a dot kept as written (TSUL-1.1, 1d); sorted by name
	if (p.type === 'options') lines.push(`\t\toptions: [${p.options.map((o) => ({ n: optName(o), o })).sort((a, b) => a.n.localeCompare(b.n)).map(({ n, o }) => `{ name: ${q(n)}, value: ${q(o)} }`).join(', ')}],`);
	if (p.type === 'number' && /limit/i.test(p.name)) lines.push(`\t\ttypeOptions: { minValue: 1 },`);
	lines.push(`\t\tdescription: ${q(p.description)},`);
	if (ops) lines.push(`\t\tdisplayOptions: { show: { resource: [${q(resource)}], operation: [${ops.map(q).join(', ')}] } },`);
	if (p.send !== 'path') {
		const drop = !p.required && (p.type === 'string' || p.type === 'number');
		lines.push(`\t\trouting: { send: { type: ${q(p.send)}, property: ${q(p.property)}${drop ? `, value: '={{ $value || undefined }}'` : ''} } },`);
	}
	lines.push(`\t},`);
	return lines.join('\n');
}

/** One resource's file: its Operation selector (options in name order, as the linter wants) and every parameter. */
function emit(resource, rows, src) {
	const ops = [...rows].sort(byName);
	const paged = rows.some((o) => o.params.some((p) => isLimit(o, p)));
	const out = [
		`// @generated by scripts/gen-descriptions.mjs from coord-lang/n8n-resale.json (coord lang/cue/n8n-resale.cue node_ops,`,
		`// checked ${src.checked?.at ?? '—'} against the live OpenAPI: ${src.checked?.paths ?? '—'} paths) — do not edit; change the row in coord, run \`coord gen\`, then this script.`,
		`import type { INodeProperties } from 'n8n-workflow';`,
		...(paged ? [`import { returnAllLimit } from './paging';`] : []),
		``,
		`/** ${rows[0].resource_name}: ${ops.map((o) => `${o.name} (${o.method} /v1${o.url.replace(/^=/, '').replace(/\{\{\$parameter\.(\w+)\}\}/g, '{$1}')})`).join(' · ')} */`,
		`export const ${resource}Operations: INodeProperties[] = [`,
		`\t{`,
		`\t\tdisplayName: 'Operation',`,
		`\t\tname: 'operation',`,
		`\t\ttype: 'options',`,
		`\t\tnoDataExpression: true,`,
		`\t\tdisplayOptions: { show: { resource: [${q(resource)}] } },`,
		`\t\toptions: [`,
		...ops.map((o) => [`\t\t\t{`, `\t\t\t\tname: ${q(o.name)},`, `\t\t\t\tvalue: ${q(o.operation)},`, `\t\t\t\taction: ${q(o.action)},`, `\t\t\t\tdescription: ${q(o.description)},`, `\t\t\t\trouting: { request: { method: ${q(o.method)}, url: ${q(o.url)} } },`, `\t\t\t},`].join('\n')),
		`\t\t],`,
		// the default is the resource's FIRST row in coord's order (a saved workflow omits a default parameter: it must not move)
		`\t\tdefault: ${q(rows[0].operation)},`,
		`\t},`,
	];
	// a required (or path) parameter shared by name across operations (none today) is emitted once, shown on every op that has it
	const seen = new Map();
	for (const o of rows) for (const p of o.params) if (p.required || p.send === 'path') (seen.get(p.name) ?? seen.set(p.name, { p, ops: [] }).get(p.name)).ops.push(o.operation);
	for (const { p, ops: on } of seen.values()) out.push(param(resource, on, p));
	// then per operation: Return All + Limit, and the optional parameters in one collection (options sorted by name, as the linter wants)
	for (const o of rows) {
		const limit = o.params.find((p) => isLimit(o, p));
		if (limit) {
			const pg = PAGING[`${o.method} ${o.url}`];
			if (!pg) throw new Error(`${o.resource}.${o.operation}: ${o.method} ${o.url} has a limit but no PAGING row (its list key, largest page, how it pages)`);
			out.push(`\t...returnAllLimit(${q(resource)}, ${q(o.operation)}, { root: ${q(pg.root)}, max: ${pg.max}, by: ${q(pg.by)} }, { limitName: ${q(limit.name)}, defaultLimit: ${limit.default ?? 50} }),`);
		}
		const rest = o.params.filter((p) => !p.required && p.send !== 'path' && p !== limit).sort((a, b) => a.display.localeCompare(b.display));
		if (!rest.length) continue;
		const c = collectionOf(o);
		const nest = (text) => text.split('\n').map((l) => `\t\t${l}`).join('\n');
		out.push(
			`\t{`,
			`\t\tdisplayName: ${q(c.display)},`,
			`\t\tname: ${q(c.name)},`,
			`\t\ttype: 'collection',`,
			`\t\tplaceholder: ${q(c.placeholder)},`,
			`\t\tdefault: {},`,
			`\t\tdisplayOptions: { show: { resource: [${q(resource)}], operation: [${q(o.operation)}] } },`,
			`\t\toptions: [`,
			...rest.map((p) => nest(param(resource, null, p))),
			`\t\t],`,
			`\t},`,
		);
	}
	out.push(`];`, ``);
	return out.join('\n');
}

export function generate(src) {
	const files = new Map();
	for (const o of src.node_ops.filter((x) => !x.hand)) (files.get(o.file) ?? files.set(o.file, []).get(o.file)).push(o);
	const out = new Map();
	for (const [file, rows] of files) {
		const res = new Set(rows.map((r) => r.resource));
		if (res.size !== 1) throw new Error(`${file}: one resource per generated file (has ${[...res].join(', ')})`);
		out.set(file, emit(rows[0].resource, rows, src));
	}
	return out;
}

/** A hand-typed op keeps the method and url of its route: its file must still carry that exact routing.request. */
export function handDrift(src, read = (f) => readFileSync(join(DESC, f), 'utf8')) {
	const out = [];
	for (const o of src.node_ops.filter((x) => x.hand)) {
		const body = read(o.file);
		const want = `routing: { request: { method: ${q(o.method)}, url: ${q(o.url)} } }`;
		const at = body.indexOf(`value: ${q(o.operation)}`);
		if (at < 0) out.push(`${o.file}: ${o.resource}.${o.operation} is not in the file (coord node_ops says it is hand-typed there)`);
		else if (!body.slice(at, at + 800).includes(want)) out.push(`${o.file}: ${o.resource}.${o.operation} does not send ${o.method} ${o.url} (its gate route ${o.method} /v1/${o.op})`);
	}
	return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const check = process.argv.includes('--check');
	if (!existsSync(SRC)) { console.log(`skip  ${SRC} is absent (the public mirror): nothing to check`); process.exit(0); }
	const src = JSON.parse(readFileSync(SRC, 'utf8'));
	const problems = [];
	for (const [file, body] of generate(src)) {
		const path = join(DESC, file);
		if (check) { if (!existsSync(path) || readFileSync(path, 'utf8') !== body) problems.push(`${file}: not what coord-lang/n8n-resale.json emits (run node scripts/gen-descriptions.mjs)`); }
		else { writeFileSync(path, body); console.log(`wrote nodes/Taifoon/descriptions/${file}`); }
	}
	problems.push(...handDrift(src));
	if (problems.length) { for (const p of problems) console.log(`FAIL  ${p}`); process.exit(1); }
	if (check) console.log(`ok    the generated descriptions are what coord-lang/n8n-resale.json emits; every hand-typed op matches its route (${src.node_ops.length} ops)`);
}
